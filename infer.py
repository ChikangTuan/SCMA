import argparse
from contextlib import contextmanager, nullcontext
from pathlib import Path

import numpy as np
import torch

from scma.data import load_condition, read_measurement
from scma.flow import sample
from scma.model import VelocityUNet
from scma.pcc import solve_pcc


@contextmanager
def pcc_correction(case, device, rho):
    measured, trace = read_measurement(case)
    if device.type == "cuda":
        from scma.geometry_cuda import CudaFanBeam640
        from scma.pcc_torch import solve_pcc_torch

        measured = torch.from_numpy(measured).to(device)
        trace = torch.from_numpy(trace).to(device)
        with CudaFanBeam640(device) as projector:
            def correct(endpoint):
                value = solve_pcc_torch(endpoint[0, 0], measured, trace, projector, rho=rho)
                return value.reshape_as(endpoint)

            yield correct
    else:
        from scma.geometry import FanBeam640

        with FanBeam640() as projector:
            def correct(endpoint):
                estimate = endpoint[0, 0].detach().cpu().numpy()
                corrected = solve_pcc(estimate, measured, trace, projector, rho=rho)
                return torch.from_numpy(corrected).to(endpoint).reshape_as(endpoint)

            yield correct


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--case", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--steps", type=int, default=50)
    parser.add_argument("--rho", type=float, default=1.0)
    parser.add_argument("--omega", type=float, default=0.5)
    parser.add_argument("--no-pcc", action="store_true")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--pcc-device", choices=("cuda", "cpu"))
    args = parser.parse_args()
    if (args.steps < 1 or args.output.suffix.lower() != ".npy"
            or not 0 < args.rho < float("inf") or not 0 <= args.omega < float("inf")):
        parser.error("expected positive steps, finite rho > 0, finite omega >= 0 and a .npy output")
    if args.output.exists():
        parser.error("output already exists")
    device = torch.device(args.device)
    if args.pcc_device == "cuda" and device.type != "cuda":
        parser.error("--pcc-device cuda requires --device cuda")
    model = VelocityUNet()
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    if not isinstance(checkpoint, dict) or checkpoint.get("format") != "scma-paper-v1":
        parser.error("expected a checkpoint generated by train.py")
    model.load_state_dict(checkpoint["model"], strict=True)
    del checkpoint
    model.to(device).eval()
    condition = load_condition(args.case).unsqueeze(0).to(device)
    torch.manual_seed(args.seed)
    pcc_device = torch.device("cpu") if args.pcc_device == "cpu" else device
    correction = nullcontext(None) if args.no_pcc else pcc_correction(args.case, pcc_device, args.rho)
    with correction as correct:
        result = sample(model, condition, correct_endpoint=correct, steps=args.steps, omega=args.omega)
    image = result[0, 0].cpu().numpy()
    if not np.isfinite(image).all():
        raise ArithmeticError("nonfinite reconstruction")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("xb") as stream:
        np.save(stream, image, allow_pickle=False)


if __name__ == "__main__":
    main()
